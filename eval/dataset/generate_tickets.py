PARAPHRASE_PREFIX = [
    "", "", "",
    "Hi there,\n\n",
    "Hello support,\n\n",
    "Hey,\n\n",
    "Quick one - ",
    "Urgent: ",
]
PARAPHRASE_SUFFIX = [
    "", "", "",
    "\n\nThanks.",
    "\n\nAny help appreciated.",
    "\n\nRegards,\nSam",
    "\n\nPlease advise ASAP.",
]


def _fill(text: str, rng: random.Random) -> str:
    out = text
    for key, options in FILLERS.items():
        token = "{" + key + "}"
        while token in out:
            out = out.replace(token, rng.choice(options), 1)
    return out


def generate(count: int = 150, seed: int = SEED) -> list[dict[str, object]]:
    rng = random.Random(seed)
    tickets: list[dict[str, object]] = []
    for i in range(count):
        t = TEMPLATES[i % len(TEMPLATES)]
        subject = _fill(t.subject, rng)
        body = rng.choice(PARAPHRASE_PREFIX) + _fill(t.body, rng) + rng.choice(PARAPHRASE_SUFFIX)
        tickets.append(
            {
                "ticket_id": f"T-{1000 + i}",
                "subject": subject,
                "body": body,
                "channel": t.channel,
                "priority": t.priority,
                "customer_tier": rng.choice(["standard", "standard", "premium", "enterprise"]),
                "product_area": t.product_area,
                "relevant_docs": list(t.relevant_docs),
                "expected_route": t.expected_route,
            }
        )
    return tickets


def main() -> None:
    tickets = generate()
    with OUT.open("w", encoding="utf-8") as fh:
        for t in tickets:
            fh.write(json.dumps(t, ensure_ascii=False) + "\n")
    print(f"wrote {len(tickets)} tickets to {OUT}")


if __name__ == "__main__":
    main()
